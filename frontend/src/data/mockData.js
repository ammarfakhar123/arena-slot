export const generateDailySlots = (sport, offPeakPrice, peakPrice) => {
  const times = [
    { time: '09:00 AM - 10:00 AM', isPeak: false },
    { time: '10:00 AM - 11:00 AM', isPeak: false },
    { time: '11:00 AM - 12:00 PM', isPeak: false },
    { time: '12:00 PM - 01:00 PM', isPeak: false },
    { time: '01:00 PM - 02:00 PM', isPeak: false },
    { time: '02:00 PM - 03:00 PM', isPeak: false },
    { time: '03:00 PM - 04:00 PM', isPeak: false },
    { time: '04:00 PM - 05:00 PM', isPeak: false },
    { time: '05:00 PM - 06:00 PM', isPeak: true },
    { time: '06:00 PM - 07:00 PM', isPeak: true },
    { time: '07:00 PM - 08:00 PM', isPeak: true },
    { time: '08:00 PM - 09:00 PM', isPeak: true },
    { time: '09:00 PM - 10:00 PM', isPeak: true },
    { time: '10:00 PM - 11:00 PM', isPeak: true },
    { time: '11:00 PM - 12:00 AM', isPeak: true },
  ];

  return times.map((t, idx) => ({
    id: `slot-${idx + 1}`,
    time: t.time,
    isPeak: t.isPeak,
    price: Math.round(t.isPeak ? peakPrice : offPeakPrice),
    status: idx === 11 || idx === 12 ? 'booked' : 'available',
    sport,
  }));
};

